import { invoke } from '@tauri-apps/api/core';
import type {
  AppSettings,
  BackupResult,
  ChatMessage,
  ConnectionReport,
  ExportResult,
  Group,
  OverlaySnapshot,
  Peer,
  PermissionStatus,
  PlatformBridge,
} from './index';

/** Tauri implementation. All native calls stay inside the bridge package. */
export const tauriBridge: PlatformBridge = {
  listPeers: () => invoke<Peer[]>('list_peers'),
  listMessages: (chatId) => invoke<ChatMessage[]>('list_messages', { chatId }),
  sendMessage: (chatId, text) => invoke<ChatMessage>('send_message', { chatId, text }),
  overlaySnapshot: () => invoke<OverlaySnapshot>('overlay_snapshot'),
  toggleCompact: () => invoke<void>('toggle_compact'),
  hideCompact: () => invoke<void>('hide_compact'),
  openFullApp: (chatId) => invoke<void>('open_full_app', { chatId }),
  setOverlayHitRegions: (hasHit) => invoke<void>('set_overlay_hit_regions', { hasHit }),
  setOverlayPointerCapture: (active, hasHit) => invoke<void>('set_overlay_pointer_capture', { active, hasHit }),
  startOverlayDrag: () => invoke<void>('start_overlay_drag'),
  moveOverlayBy: (deltaX, deltaY) => invoke<void>('move_overlay_by', { deltaX, deltaY }),
  endOverlayDrag: (hasHit, reduceMotion) => invoke<void>('end_overlay_drag', { hasHit, reduceMotion }),
  resizeDock: (hasBubbles) => invoke<void>('resize_dock', { hasBubbles }),
  openDockMenu: () => invoke<void>('open_dock_menu'),
  hideMenu: () => invoke<void>('hide_menu'),
  quit: () => invoke<void>('quit_app'),
  resetOverlayPosition: () => invoke<void>('reset_overlay_position'),
  setSnapToEdge: (enabled) => invoke<void>('set_snap_to_edge', { enabled }),
  setBubbleSettings: (enabled, autoHideSeconds) => invoke<void>('set_bubble_settings', { enabled, autoHideSeconds }),
  markAsRead: (chatId) => invoke<void>('mark_as_read', { chatId }),
  deleteMessageLocal: (messageId) => invoke<boolean>('delete_message_local', { messageId }),
  editMessageLocal: (messageId, text) => invoke<boolean>('edit_message_local', { messageId, text }),
  getMyIdentity: () => invoke<{ peerId: string; fingerprint: string }>('get_my_identity'),
  getSettings: () => invoke<AppSettings>('get_settings'),
  updateSettings: (patch) => invoke<AppSettings>('update_settings', { patch }),
  setLaunchAtLogin: (enabled) => invoke<boolean>('set_launch_at_login', { enabled }),
  setHotkey: (combo) => invoke<string>('set_hotkey', { combo }),
  isDndActive: () => invoke<boolean>('is_dnd_active'),
  setLanPassphrase: (passphrase) => invoke<boolean>('set_lan_passphrase', { passphrase }),
  hasLanPassphrase: () => invoke<boolean>('has_lan_passphrase'),
  permissionStatus: (kind) => invoke<PermissionStatus>('permission_status', { kind }),
  openPermissionSettings: (kind) => invoke<void>('open_permission_settings', { kind }),
  openFirewallGuide: () => invoke<string[]>('open_firewall_guide'),
  runConnectionTest: () => invoke<ConnectionReport>('run_connection_test'),
  createBackup: (passphrase) => invoke<BackupResult>('create_backup', { passphrase }),
  listBackups: () => invoke<BackupResult[]>('list_backups'),
  restoreBackup: (path, passphrase) => invoke<void>('restore_backup', { path, passphrase }),
  exportData: () => invoke<ExportResult>('export_data'),
  revealPath: (path) => invoke<void>('reveal_path', { path }),
  setMutedChat: (chatId, muted) => invoke<string[]>('set_muted_chat', { chatId, muted }),
  listGroups: () => invoke<Group[]>('list_groups'),
  createGroup: (name, memberIds, icon) => invoke<Group>('create_group', { name, memberIds, icon }),
  updateGroup: (id, patch) => invoke<Group>('update_group', { id, patch }),
  addGroupMembers: (id, memberIds) => invoke<Group>('add_group_members', { id, memberIds }),
  removeGroupMember: (id, peerId) => invoke<Group>('remove_group_member', { id, peerId }),
  leaveGroup: (id) => invoke<void>('leave_group', { id }),
  setAvatar: (avatarDataUrl) => invoke<string | null>('set_avatar', { avatarDataUrl }),
  getAvatar: () => invoke<string | null>('get_avatar'),
};
