/** The full icon registry type; keys are the `name` values accepted by `<Icon>`. */
export type IconMap = typeof ICONS;
export type IconName = keyof IconMap;

/** Every registered glyph, for storyboards and design-system overviews. */
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

export type IconProps = {
  name: IconName;
  /** Defaults to the 20px icon size from the context-menu spec. */
  size?: number;
  className?: string;
  strokeWidth?: number;
  /** Solid variant, used for the brand mark and the send glyph. */
  filled?: boolean;
  /** Rotate animation, used by the "sending" tick and loading buttons. */
  spin?: boolean;
  /** When set the glyph is exposed to assistive tech; otherwise it is decorative. */
  label?: string;
};

/** Joins class names, dropping anything falsy. */
export function cx(...parts: Array<string | false | null | undefined>): string {
  return parts.filter((part): part is string => Boolean(part)).join(' ');
}

export function Icon({
  name,
  size = 20,
  className,
  strokeWidth,
  filled = false,
  spin = false,
  label,
}: IconProps) {
  const Glyph = ICONS[name];
  return (
    <Glyph
      aria-hidden={label ? undefined : true}
      aria-label={label}
      className={cx('ac-icon', filled && 'ac-icon--filled', spin && 'ac-icon--spin', className)}
      role={label ? 'img' : undefined}
      size={size}
      strokeWidth={strokeWidth}
    />
  );
}
